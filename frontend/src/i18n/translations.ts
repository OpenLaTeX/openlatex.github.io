export type Language = keyof typeof translations;

export const defaultLanguage: Language = 'fr';

export const languageCodes = Object.keys(translations) as Language[];

export const resolveLanguage = (value?: string): Language =>
  languageCodes.includes(value as Language) ? value as Language : defaultLanguage;

export const languageOptions = languageCodes.map((value) => ({
  value,
  label: translations[value].languageName
}));

export const resources = Object.fromEntries(
  languageCodes.map((language) => [language, { translation: translations[language] }])
);
